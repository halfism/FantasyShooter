# -*- coding: utf-8 -*-
"""把 ArtSource/Downloaded 下的 Kenney CC0 包（OBJ 格式）导入工程。

两个必须做的几何变换（在转换后的 OBJ 里完成，导入器保持 1:1）：

1. **Y-up -> Z-up**：Kenney 的模型是 Y 轴向上（顶点 Y[0, h]，基座在 Y=0）。
   直接导入会躺倒。映射 (x, y, z) -> (x, -z, y)。
   （上一轮已实测：OBJ 导入 1:1、不翻轴、不缩单位，所以只要喂进去是 Z-up，
   导出来就是 Z-up。）
2. **米 -> 厘米**：模型是 1 unit = 1m，UE 是 1uu = 1cm，所以乘 100。
   做完后资产本身就是真实尺度，编辑器里看着也正常。

材质：**不用贴图**。Kenney 全部模型共用一张 colormap.png，本来想按官方预览还原
颜色，但这条无界面导入链路（`-nullrhi` commandlet）拿不到有效的 GPU 贴图资源：
资产在 CPU 侧是 512x512 且内容正确，`GetSizeX()` 却恒为 32x32，采出来全黑。
所以改成「低多边形纯色 + 按模型类别上色」，与工程本身的纯色自发光几何一致：
每个包一个 **Unlit + VectorParameter("Tint") -> EmissiveColor** 材质，
具体颜色由 C++ 侧 `FSUtil::PropColor()` 按模型名决定。

跑法：
  UnrealEditor-Cmd.exe <abs uproject> -run=pythonscript -script="<abs this>" \
     -nullrhi -nosplash -nop4 -stdout
"""
import os
import re
import shutil
import unreal

ROOT = r"G:/Epic/UnrealProjects/FantasyShooter58"
DL = os.path.join(ROOT, "ArtSource", "Downloaded")
CONV = os.path.join(ROOT, "ArtSource", "Converted")

SCALE = 100.0
SLUGS = ["survival-kit", "castle-kit", "graveyard-kit", "fantasy-town-kit", "mini-dungeon"]

MESH_DST = "/Game/Art/Props"
TEX_DST = "/Game/Art/Textures"
MAT_DST = "/Game/Art/Materials"


def slug_id(slug):
    return slug.replace("-", "_")


def safe_name(stem):
    return re.sub(r"[^A-Za-z0-9_]", "_", stem)


def convert_obj(src_path, dst_path, scale, mtl_name="art.mtl"):
    """Y-up 米制 -> Z-up 厘米制。

    **必须保留 mtllib/usemtl**：Interchange 只有在 OBJ 声明了材质时才会导入 UV，
    删掉之后 mesh 没有 UV 通道，TextureSample 采样 UV0=(0,0) —— 正好是调色板
    左上角的纯黑，于是所有道具渲染成全黑、在黑底场景里完全看不见。
    这里把所有 OBJ 统一指向同一个 art.mtl（内容由 write_shared_mtl 生成），
    这样每个包只会产生一个材质，也不会因为 400 多个 mtl 名而散架。

    另外去掉 `g` 组名：Interchange 会用 group 名当资产名，`g campfire-pit`
    会让 destination_name 失效，没有 g 行的则变成垃圾资产 "Group"。
    """
    out = []
    with open(src_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            if line.startswith("v "):
                a = line.split()
                x, y, z = float(a[1]), float(a[2]), float(a[3])
                out.append("v %.6f %.6f %.6f\n" % (x * scale, -z * scale, y * scale))
            elif line.startswith("vn "):
                a = line.split()
                x, y, z = float(a[1]), float(a[2]), float(a[3])
                ny, nz = -z, y
                ln = (x * x + ny * ny + nz * nz) ** 0.5 or 1.0
                out.append("vn %.6f %.6f %.6f\n" % (x / ln, ny / ln, nz / ln))
            elif line.startswith("vt "):
                # **不要翻 V**。Kenney 的 colormap 上半部（v<0.45）是纯黑占位区，
                # 原始 UV 正好落在 0.525~0.975（彩色行 + 灰棕肤色区）。
                # 曾经按"OBJ 原点在左下、UE 在左上"翻过一次，结果 UV 变成 0.025~0.475，
                # 整片采到黑区 —— 道具全黑、在黑底场景里完全隐形。
                a = line.split()
                u, v = float(a[1]), float(a[2])
                out.append("vt %.6f %.6f\n" % (u, v))
            elif line.startswith("mtllib "):
                out.append("mtllib %s\n" % mtl_name)
            elif line.startswith("usemtl "):
                out.append("usemtl colormap\n")
            elif line.startswith(("g ", "o ")):
                continue
            else:
                out.append(line)
    with open(dst_path, "w", encoding="utf-8") as f:
        f.writelines(out)


def write_shared_mtl(dst_dir, tex_file="colormap.png"):
    """所有 OBJ 共用的材质定义：只引用调色板贴图，颜色由贴图决定。"""
    path = os.path.join(dst_dir, "art.mtl")
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Kenney CC0 colormap (auto-generated by import_props.py)\n")
        f.write("newmtl colormap\n")
        f.write("Ka 1 1 1\nKd 1 1 1\nKs 0 0 0\nNs 10\nillum 1\n")
        f.write("map_Kd %s\n" % tex_file)


def convert_pack(slug):
    src = os.path.join(DL, slug, "Models", "OBJ format")
    if not os.path.isdir(src):
        unreal.log_warning("[FSPROP] skip %s (no OBJ format)" % slug)
        return None

    dst = os.path.join(CONV, slug)
    os.makedirs(dst, exist_ok=True)

    # 找 colormap：读任一 mtl 的 map_Kd
    tex_src = None
    tex_dir = os.path.join(src, "Textures")
    if os.path.isdir(tex_dir):
        for f in sorted(os.listdir(tex_dir)):
            if f.lower().endswith(".png"):
                tex_src = os.path.join(tex_dir, f)
                break
    if tex_src is None:
        for f in sorted(os.listdir(src)):
            if f.lower().endswith(".mtl"):
                for line in open(os.path.join(src, f), encoding="utf-8", errors="ignore"):
                    if line.lower().startswith("map_kd"):
                        cand = os.path.join(src, line.split(None, 1)[1].strip())
                        if os.path.exists(cand):
                            tex_src = cand
                        break
                if tex_src:
                    break

    converted = []
    for f in sorted(os.listdir(src)):
        if not f.lower().endswith(".obj"):
            continue
        stem = safe_name(os.path.splitext(f)[0])
        out_obj = os.path.join(dst, stem + ".obj")
        convert_obj(os.path.join(src, f), out_obj, SCALE)
        converted.append(stem)

    tex_dst = os.path.join(dst, "colormap.png")
    if tex_src:
        shutil.copyfile(tex_src, tex_dst)
    write_shared_mtl(dst)
    unreal.log("[FSPROP] %s converted=%d tex=%s" % (slug, len(converted), bool(tex_src)))
    return {"slug": slug, "mesh_dir": dst, "stems": converted, "tex": tex_dst if tex_src else None}




def build_material(pack):
    """Unlit + VectorParameter("Tint") -> EmissiveColor（纯色，不采样贴图）。

    贴图在这条 -nullrhi 导入链路上用不了：CPU 侧数据是 512x512 且内容正确，
    但资产的 GPU 资源恒为 32x32 占位，采出来全黑（详见模块 docstring）。
    所以颜色完全交给 Tint：C++ 侧按模型名分类上色，同色 MID 共享。
    """
    sid = slug_id(pack["slug"])
    name = "M_Art_%s" % sid
    path = MAT_DST + "/" + name

    if unreal.EditorAssetLibrary.does_asset_exist(path):
        unreal.EditorAssetLibrary.delete_asset(path)

    tools = unreal.AssetToolsHelpers.get_asset_tools()
    mat = tools.create_asset(name, MAT_DST, unreal.Material, unreal.MaterialFactoryNew())
    if not mat:
        unreal.log_error("[FSPROP] material create failed %s" % name)
        return None

    mel = unreal.MaterialEditingLibrary
    try:
        mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    except Exception as e:
        unreal.log_warning("[FSPROP] shading_model set failed: %s" % e)

    # 默认灰：没被 PropColor 分类到的模型也不会是纯白刺眼的一团
    param = mel.create_material_expression(mat, unreal.MaterialExpressionVectorParameter, -360, 0)
    param.set_editor_property("parameter_name", "Tint")
    param.set_editor_property("default_value", unreal.LinearColor(0.42, 0.42, 0.46, 1.0))

    mel.connect_material_property(param, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)

    mel.recompile_material(mat)
    unreal.EditorAssetLibrary.save_asset(path)
    return unreal.EditorAssetLibrary.load_asset(path)


def import_meshes(pack, mat):
    sid = slug_id(pack["slug"])
    dst = MESH_DST + "/" + sid

    tasks = []
    for stem in pack["stems"]:
        t = unreal.AssetImportTask()
        t.set_editor_property("filename", os.path.join(pack["mesh_dir"], stem + ".obj"))
        t.set_editor_property("destination_path", dst)
        t.set_editor_property("destination_name", stem)
        t.set_editor_property("automated", True)
        t.set_editor_property("replace_existing", True)
        t.set_editor_property("save", True)
        tasks.append(t)

    unreal.log("[FSPROP] %s importing %d meshes -> %s" % (pack["slug"], len(tasks), dst))
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

    # 清掉上一轮遗留的意外资产：Group（OBJ 无 g 行时 Interchange 的默认名）
    # 和带连字符的名字（g 行覆盖 destination_name 的产物）。
    want = set(pack["stems"])
    if unreal.EditorAssetLibrary.does_directory_exist(dst):
        for a in unreal.EditorAssetLibrary.list_assets(dst, recursive=False):
            short = a.split("/")[-1].split(".")[0]
            if short not in want:
                unreal.EditorAssetLibrary.delete_asset(a)
                unreal.log("[FSPROP] removed stray %s/%s" % (slug_id(pack["slug"]), short))

    sub = unreal.get_editor_subsystem(unreal.StaticMeshEditorSubsystem)
    rows = []
    for stem in pack["stems"]:
        path = dst + "/" + stem
        if not unreal.EditorAssetLibrary.does_asset_exist(path):
            unreal.log_error("[FSPROP] MESH MISSING %s" % stem)
            continue
        mesh = unreal.EditorAssetLibrary.load_asset(path)
        if mat is not None:
            # StaticMeshEditorSubsystem 在 commandlet 下拿到的是 None，
            # 所以直接改写 StaticMaterials 数组（ImportedMaterialSlotName 是只读的，不碰）。
            try:
                old = mesh.get_editor_property("static_materials")
                new = []
                if old:
                    for s in old:
                        sm = unreal.StaticMaterial()
                        sm.set_editor_property("material_interface", mat)
                        sm.set_editor_property("material_slot_name",
                                               s.get_editor_property("material_slot_name"))
                        new.append(sm)
                else:
                    sm = unreal.StaticMaterial()
                    sm.set_editor_property("material_interface", mat)
                    sm.set_editor_property("material_slot_name", "ColorMap")
                    new.append(sm)
                mesh.set_editor_property("static_materials", new)
            except Exception as e:
                unreal.log_warning("[FSPROP] set_material %s: %s" % (stem, e))
            unreal.EditorAssetLibrary.save_asset(path)
        b = mesh.get_bounds()
        e, o = b.box_extent, b.origin
        rows.append((stem, e.x, e.y, e.z, o.z, mesh.get_num_triangles(0)))
    return rows


def main():
    # 贴图目录已经不需要了（材质是纯色）；顺手把早期导入留下的 T_<slug>_Art 清掉，
    # 否则它会被 DirectoriesToAlwaysCook 一起打进包里。
    if unreal.EditorAssetLibrary.does_directory_exist(TEX_DST):
        for slug in SLUGS:
            stale = "%s/T_%s_Art" % (TEX_DST, slug_id(slug))
            if unreal.EditorAssetLibrary.does_asset_exist(stale):
                unreal.EditorAssetLibrary.delete_asset(stale)
                unreal.log("[FSPROP] removed unused texture %s" % stale)

    if not unreal.EditorAssetLibrary.does_directory_exist(MAT_DST):
        unreal.EditorAssetLibrary.make_directory(MAT_DST)

    summary = []
    for slug in SLUGS:
        pack = convert_pack(slug)
        if not pack:
            continue
        mat = build_material(pack)
        rows = import_meshes(pack, mat)
        for r in rows:
            unreal.log("[FSPROP] %-22s ext=(%.1f,%.1f,%.1f) zmin=%.1f tris=%d"
                       % (slug_id(slug) + "/" + r[0], r[1], r[2], r[3], r[4], r[5]))
        summary.append((slug, len(rows)))

    unreal.log("[FSPROP] DONE %s" % ", ".join("%s:%d" % (s, n) for s, n in summary))
    unreal.log("[FSPROP] PROP_EXIT=0")


main()
